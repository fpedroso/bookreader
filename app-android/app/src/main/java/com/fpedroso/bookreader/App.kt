@Composable
fun App() {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()

    var library by remember { mutableStateOf(Store.load(ctx)) }
    var openBook by remember { mutableStateOf<BookMeta?>(null) }
    var parsed by remember { mutableStateOf<EpubParser.Book?>(null) }
    var sidecar by remember { mutableStateOf<Sidecar?>(null) }
    var loading by remember { mutableStateOf(false) }
    var showPinyin by remember { mutableStateOf(true) }
    var lang by remember { mutableStateOf("zh") }
    var dict by remember { mutableStateOf<Dictionary?>(null) }
    // Paragraph translation. The word dialog is gone: tapping a paragraph opens a modal
    // with its English translation, produced on-device by ML Kit.
    var tapPara by remember { mutableStateOf<RowItem.Para?>(null) }
    var translation by remember { mutableStateOf<String?>(null) }
    var translating by remember { mutableStateOf(false) }
    var translateError by remember { mutableStateOf<String?>(null) }
    var translations by remember { mutableStateOf<Map<String, String>>(emptyMap()) }
    var lastIndex by remember { mutableStateOf(0) }
    // Readings generated in-app, by block hash. Separate from the rows so a row can pick
    // its readings up without the row list being rebuilt.
    var generated by remember { mutableStateOf<Map<String, List<Token>>>(emptyMap()) }
    var lastPersistAt by remember { mutableStateOf(0L) }
    var lastTransPersist by remember { mutableStateOf(0L) }

    val picker = rememberLauncherForActivityResult(
        ActivityResultContracts.OpenMultipleDocuments()
    ) { uris ->
        if (uris.isNullOrEmpty()) return@rememberLauncherForActivityResult
        scope.launch {
            withContext(Dispatchers.IO) { importPicked(ctx, uris) }
            library = Store.load(ctx)
        }
    }

    // Parse on open, off the main thread: a novel's sidecar can be ~12 MB.
    LaunchedEffect(openBook) {
        val b = openBook ?: return@LaunchedEffect
        loading = true
        generated = emptyMap()
        translations = emptyMap()
        tapPara = null
        var loadedTranslations: Map<String, String> = emptyMap()
        val result = withContext(Dispatchers.IO) {
            val p = runCatching { EpubParser.parse(File(b.epubFile)) }.getOrNull()
            // A PC sidecar wins. Otherwise reuse whatever was generated in-app on an
            // earlier open, so a second read of the same book generates nothing.
            val s = b.sidecarFile?.let { runCatching { Annotations.load(it) }.getOrNull() }
                ?: runCatching { Annotations.load(genPath(ctx, b.id).absolutePath) }.getOrNull()
            // A sidecar only exists for Chinese, so its lang wins; otherwise trust the
            // EPUB's dc:language, and fall back to how the book was imported.
            val bookLang = s?.lang ?: p?.language ?: b.lang
            val d: Dictionary =
                if (bookLang.startsWith("de")) GermanDict(ctx) else ChineseDict(ctx)
            // Deliberately NOT warmed any more: word lookup is off for now, and warming
            // copies de.db (>100 MB) out of the APK for a feature nothing calls.
            // Translations cached on an earlier read, keyed by block hash.
            val t: Map<String, String> = runCatching {
                Json.decodeFromString(
                    Translations.serializer(),
                    transPath(ctx, b.id).readText(Charsets.UTF_8),
                ).blocks
            }.getOrNull().orEmpty()
            loadedTranslations = t
            Triple(p, s, bookLang to d)
        }
        parsed = result.first
        sidecar = result.second
        lang = result.third.first
        dict = result.third.second
        translations = loadedTranslations
        loading = false
    }

    /** Leave the book, persisting the reading position once. */
    val closeBook: () -> Unit = {
        val b = openBook
        if (b != null) {
            Store.setProgress(ctx, b.id, lastIndex)
            // Keep this session's readings so the next open is instant. Off the main
            // thread: the file reaches tens of MB for a novel.
            val snapshot = generated
            if (snapshot.isNotEmpty()) {
                scope.launch { withContext(Dispatchers.IO) { persistGenerated(ctx, b.id, snapshot) } }
            }
            val tr = translations
            if (tr.isNotEmpty()) {
                scope.launch { withContext(Dispatchers.IO) { persistTranslations(ctx, b.id, tr) } }
            }
        }
        library = Store.load(ctx)
        openBook = null
        parsed = null
        sidecar = null
        generated = emptyMap()
        translations = emptyMap()
    }

    // The system back gesture must behave like the in-app "←" rather than finishing the
    // Activity. It also closes the translation modal first, since that sits on top.
    BackHandler(enabled = openBook != null || tapPara != null) {
        if (tapPara != null) tapPara = null else closeBook()
    }

    val current = openBook
    if (current == null) {
        LibraryScreen(
            books = library.books,
            onImport = { picker.launch(arrayOf("application/epub+zip", "application/json", "*/*")) },
            onOpen = { openBook = it },
            onDelete = {
                Store.remove(ctx, it.id)
                library = Store.load(ctx)
            },
        )
    } else if (loading || parsed == null) {
        Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) { Text("Loading…") }
    } else {
        val book = parsed!!
        val rows = remember(book, sidecar, lang) { buildRows(book, sidecar, lang) }

        // Chinese with no sidecar: generate readings as you read, on demand.
        //
        // Deliberately NOT part of opening the book. The book renders plain immediately
        // and pinyin drops in when it is ready, so generation can never block reading -
        // and it is windowed rather than end-to-end, because annotating a novel up front
        // would take minutes. A book in any other language never enters this effect.
        LaunchedEffect(book, sidecar, lang) {
            if (!lang.startsWith("zh") || sidecar != null) return@LaunchedEffect
            snapshotFlow { lastIndex }.collectLatest { at ->
                val from = (at - 40).coerceAtLeast(0)
                val to = (at + 160).coerceAtMost(rows.size)
                val pending = ArrayList<Pair<String, String>>()
                for (i in from until to) {
                    val r = rows[i]
                    if (r is RowItem.Para && r.tokens == null) {
                        val h = r.hash ?: continue
                        if (!generated.containsKey(h)) pending.add(h to r.text)
                    }
                }
                if (pending.isEmpty()) return@collectLatest
                val done = withContext(Dispatchers.Default) {
                    pending.mapNotNull { (h, text) ->
                        PinyinGen.annotate(ctx, text)?.let { h to it }
                    }
                }
                if (done.isEmpty()) return@collectLatest
                generated = generated + done
                // Throttled: re-encoding a large map on every scroll would cost more than
                // the annotation itself. closeBook always writes a final copy.
                val now = System.currentTimeMillis()
                if (now - lastPersistAt > 15_000) {
                    lastPersistAt = now
                    val snapshot = generated
                    withContext(Dispatchers.IO) { persistGenerated(ctx, current.id, snapshot) }
                }
            }
        }

        // Tap a paragraph -> its translation, cached by block hash so re-tapping is free.
        // Off the main thread: the first call in a language also downloads its model.
        val onParagraphTap: (RowItem.Para) -> Unit = { para ->
            tapPara = para
            val h = para.hash
            val cached = h?.let { translations[it] }
            translation = cached
            translateError = null
            translating = cached == null && h != null
            if (cached == null && h != null) {
                scope.launch {
                    val res = runCatching {
                        withContext(Dispatchers.Default) {
                            Translate.paragraph(ctx, lang, para.text)
                        }
                    }
                    translating = false
                    res.fold(
                        onSuccess = { text ->
                            translation = text
                            translations = translations + (h to text)
                            // Throttled: re-encoding a growing map on every tap costs more
                            // than the translation. closeBook always writes a final copy.
                            val now = System.currentTimeMillis()
                            if (now - lastTransPersist > 5_000) {
                                lastTransPersist = now
                                val snap = translations
                                withContext(Dispatchers.IO) {
                                    persistTranslations(ctx, current.id, snap)
                                }
                            }
                        },
                        onFailure = { e ->
                            translateError = e.message ?: e.javaClass.simpleName
                        },
                    )
                }
            }
        }

        ReaderScreen(
            title = current.title,
            rows = rows,
            showPinyin = showPinyin,
            pinyinToggleVisible = lang.startsWith("zh"),
            initialIndex = current.lastBlock,
            generated = generated,
            selectedHash = tapPara?.hash,
            onTogglePinyin = { showPinyin = it },
            onParagraphTap = onParagraphTap,
            onProgress = { lastIndex = it },
            onBack = closeBook,
        )
        tapPara?.let { para ->
            TranslationDialog(
                source = para.text,
                translation = translation,
                busy = translating,
                error = translateError,
                onDismiss = { tapPara = null },
            )
        }
    }
}

private fun buildRows(book: EpubParser.Book, sidecar: Sidecar?, lang: String): List<RowItem> {
    val out = ArrayList<RowItem>()
    for (ch in book.chapters) {
        ch.title?.takeIf { it.isNotBlank() }?.let { out.add(RowItem.ChapterHead(it)) }
        for (bl in ch.blocks) {
            // Every paragraph carries its block hash: it is the key for in-app pinyin AND
            // for the translation cache, and the tap target for the translation modal.
            val hash = Annotations.key(bl.text)
            // Chinese tokens come from the PC-generated sidecar (segmentation plus
            // readings). German has no sidecar and needs none: the language is
            // space-separated, so tokenising here is enough and the dictionary
            // resolves whatever inflection the token happens to be.
            val sidecarTokens = Annotations.tokens(sidecar, bl.text)
            when {
                sidecarTokens != null ->
                    out.add(RowItem.Para(bl.text, sidecarTokens, bl.heading, hash = hash))
                lang.startsWith("de") -> {
                    // Space-separated, so render as prose and resolve taps by offset.
                    val spans = GermanTokenizer.tokenizeRanges(bl.text)
                    out.add(
                        RowItem.Para(
                            text = bl.text,
                            tokens = spans.map { it.first }.ifEmpty { null },
                            heading = bl.heading,
                            tokenRanges = spans.map { it.second }.ifEmpty { null },
                            hash = hash,
                        )
                    )
                }
                // Chinese with no sidecar: readings are generated in-app.
                lang.startsWith("zh") ->
                    out.add(RowItem.Para(bl.text, null, bl.heading, hash = hash))
                else ->
                    out.add(RowItem.Para(bl.text, null, bl.heading, hash = hash))
            }
        }
    }
    return out
}

// ------------------------------------------------------- generated pinyin cache

/** Where in-app generated readings are cached for a book. */
private fun genPath(context: Context, id: String): File =
    File(File(Store.booksDir(context), id), "pinyin.generated.json")

/** Where paragraph translations are cached for a book. */
private fun transPath(context: Context, id: String): File =
    File(File(Store.booksDir(context), id), "translations.json")

/**
 * Persist translations alongside the book, keyed by block hash - the same trick as the
 * pinyin sidecar, so a paragraph keeps its translation even if the book is re-imported.
 * Written via a temp file: a same-filesystem rename is atomic, so a crash mid-write cannot
 * leave a half-parsed cache behind.
 */
private fun persistTranslations(context: Context, id: String, blocks: Map<String, String>) {
    runCatching {
        val target = transPath(context, id)
        target.parentFile?.mkdirs()
        val tmp = File(target.parentFile, target.name + ".tmp")
        tmp.writeText(
            Json.encodeToString(Translations.serializer(), Translations(blocks = blocks)),
            Charsets.UTF_8,
        )
        if (!tmp.renameTo(target)) {
            target.delete()
            tmp.renameTo(target)
        }
    }
}

/**
 * Persist generated readings in the same sidecar format `tools/annotate.py` emits, so the
 * next open of this book takes the normal sidecar path and generates nothing.
 */
private fun persistGenerated(context: Context, id: String, blocks: Map<String, List<Token>>) {
    runCatching {
        val payload = Sidecar(
            v = 1,
            lang = "zh",
            source = "generated-in-app",
            blocks = blocks.mapValues { (_, toks) ->
                toks.map { listOf(it.word, it.pinyin, it.source) }
            },
        )
        val target = genPath(context, id)
        target.parentFile?.mkdirs()
        val tmp = File(target.parentFile, target.name + ".tmp")
        tmp.writeText(Json.encodeToString(Sidecar.serializer(), payload), Charsets.UTF_8)
        // A same-filesystem rename is atomic, so a crash mid-write cannot leave a
        // half-parsed sidecar for the next open to trip over.
        if (!tmp.renameTo(target)) {
            target.delete()
            tmp.renameTo(target)
        }
    }
}

// ------------------------------------------------------------------- import
private fun displayName(context: Context, uri: Uri): String? =
    runCatching {
        context.contentResolver.query(uri, null, null, null, null)?.use { c ->
            val i = c.getColumnIndex(OpenableColumns.DISPLAY_NAME)
            if (i >= 0 && c.moveToFirst()) c.getString(i) else null
        }
    }.getOrNull()

private fun copyIn(context: Context, uri: Uri, dest: File) {
    context.contentResolver.openInputStream(uri)?.use { input ->
        dest.outputStream().use { input.copyTo(it) }
    }
}

/**
 * The picker accepts several files at once, so selecting the EPUB together with
 * its .pinyin.json sidecar in one gesture pairs them. Both come from the PC tool.
 */
private fun importPicked(context: Context, uris: List<Uri>): Int {
    val staging = File(context.filesDir, "staging")
    staging.deleteRecursively()
    staging.mkdirs()

    val byBase = HashMap<String, MutableList<Pair<String, File>>>()
    uris.forEachIndexed { i, uri ->
        val name = displayName(context, uri) ?: "file_$i"
        val ext = when {
            name.endsWith(".epub", true) -> "epub"
            name.endsWith(".json", true) -> "json"
            else -> return@forEachIndexed
        }
        val safe = name.replace(Regex("[^A-Za-z0-9._-]"), "_")
        val dest = File(staging, "s${i}_$safe")
        runCatching { copyIn(context, uri, dest) }.getOrNull()
        if (dest.exists()) {
            byBase.getOrPut(name.substringBeforeLast('.')) { mutableListOf() }.add(ext to dest)
        }
    }

    var imported = 0
    for ((base, files) in byBase) {
        val epub = files.firstOrNull { it.first == "epub" }?.second ?: continue
        val jsonFile = files.firstOrNull { it.first == "json" }?.second

        val parsedBook = runCatching { EpubParser.parse(epub) }.getOrNull()
        val title = parsedBook?.title?.takeIf { it.isNotBlank() } ?: base
        val id = Store.idFor(title + base)

        val dir = File(Store.booksDir(context), id)
        dir.mkdirs()
        val epubDest = File(dir, "book.epub")
        epub.copyTo(epubDest, overwrite = true)
        val sidecarDest = jsonFile?.let { src ->
            File(dir, "pinyin.json").also { d -> src.copyTo(d, overwrite = true) }
        }

        Store.add(
            context,
            BookMeta(
                id = id,
                title = title,
                epubFile = epubDest.absolutePath,
                sidecarFile = sidecarDest?.absolutePath,
                // A sidecar only ever accompanies a Chinese book.
                lang = if (sidecarDest != null) "zh" else (parsedBook?.language ?: "zh"),
                addedAt = System.currentTimeMillis(),
            ),
        )
        imported++
    }
    staging.deleteRecursively()
    return imported
}
